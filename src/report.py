"""Build docs/phase3_results.md from whatever result CSVs exist (safe to call repeatedly).

    python -m src.report
"""
import argparse
import csv
import os

from src.data import SHORT_NAMES


def _read(path):
    if not os.path.exists(path):
        return []
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def _f(v, nd=2):
    try:
        x = float(v)
    except (TypeError, ValueError):
        return str(v)
    return "—" if x != x else f"{x:.{nd}f}"


def _pm(r, k, nd=3):
    return f"{_f(r[k + '_mean'], nd)} ± {_f(r[k + '_std'], nd)}"


def headline(bench, summary, times):
    out = []
    by = {r["name"]: r for r in bench}
    base = by.get("A-ddpm-1000")
    students = sorted([r for r in bench if r["run"] == "E"], key=lambda r: int(r["steps"]))
    if base and students:
        s = students[0]
        out.append(f"**{s['steps']} steps vs 1000 · {int(base['nfe']) // int(s['nfe'])}× fewer network calls · "
                   f"FID {_f(s['fid'], 1)} (student) vs {_f(base['fid'], 1)} (baseline DDPM) · "
                   f"{float(base['single_latency_ms']) / float(s['single_latency_ms']):.0f}× lower single-image latency**")
    for st in ("100%", "20%"):
        real = next((r for r in summary if r["setting"] == st and r["arm"] == "real"), None)
        syn = next((r for r in summary if r["setting"] == st and r["arm"] == "real+synthetic"), None)
        if real and syn:
            d = 100 * (float(syn["macro_f1_mean"]) - float(real["macro_f1_mean"]))
            out.append(f"Augmentation with {st} real data: macro-F1 {d:+.1f} pts "
                       f"({_f(real['macro_f1_mean'], 3)} → {_f(syn['macro_f1_mean'], 3)}).")
    st = [t for t in times if t["setting"] == "100%"]
    if len(st) >= 2:
        fast = next(t for t in st if not t["engine"].startswith("Baseline"))
        slow = next(t for t in st if t["engine"].startswith("Baseline"))
        est = " (extrapolated)" if slow["extrapolated"] == "True" else ""
        out.append(f"Synthetic set ({fast['n_images']} images): {_f(fast['seconds'], 1)} s with {fast['engine']} "
                   f"vs ~{float(slow['seconds']) / 60:.1f} min with the 1000-step baseline{est}.")
    return out


def write(results_dir="results", docs_dir="docs"):
    bench = _read(os.path.join(results_dir, "benchmark.csv"))
    summary = _read(os.path.join(results_dir, "augmentation_summary.csv"))
    times = _read(os.path.join(results_dir, "gen_time.csv"))
    judge = {r["metric"]: r["value"] for r in _read(os.path.join(results_dir, "judge.csv"))}
    rel = os.path.relpath(results_dir, docs_dir).replace("\\", "/")

    L = ["# Phase 3 — Results (auto-generated)", "",
         "_Generated by `src/evaluate.py` / `src/augment_experiment.py` via `src/report.py`. "
         "Re-run those scripts to refresh._", ""]
    hl = headline(bench, summary, times)
    if hl:
        L += ["## Headline", ""] + [f"* {h}" for h in hl] + [""]

    if bench:
        L += ["## Benchmark (quality vs. speed)", "",
              "| Config | Schedule | Target | Sampler | Steps | CFG w | Net calls / img | FID ↓ | Class acc ↑ "
              "| ms / img (batched) | Single-image latency (ms) | Samples |",
              "|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for r in bench:
            L.append(f"| {r['name']} | {r['schedule']} | {r['pred']} | {r['sampler'].upper()} | {r['steps']} | "
                     f"{_f(r['guidance'], 1)} | {r['nfe']} | {_f(r['fid'])} | {_f(r['class_acc'], 3)} | "
                     f"{_f(r['ms_per_image'], 2)} | {_f(r['single_latency_ms'], 0)} | {r['n_samples']} |")
        L += ["", "Run E is the distilled student (CFG folded in, so one network call per step). "
              "FID uses Inception features (torch-fidelity) against the DermaMNIST test split; the DDPM-1000 "
              "row uses fewer samples (it is ~50× slower), which biases its FID slightly upward.", ""]

        # ablation at a fixed small budget
        steps = sorted({int(r["steps"]) for r in bench if r["run"] in "ABCD" and r["sampler"] == "ddim"})
        L += ["## Ablation at a fixed budget (DDIM, trailing timesteps)", "",
              "| Run | Schedule | Target | " + " | ".join(f"FID @ {s}" for s in steps) + " |",
              "|---|---|---|" + "---:|" * len(steps)]
        for run in "ABCD":
            rs = {int(r["steps"]): r for r in bench if r["run"] == run and r["sampler"] == "ddim"}
            if rs:
                any_r = next(iter(rs.values()))
                L.append(f"| {run} | {any_r['schedule']} | {any_r['pred']} | " +
                         " | ".join(_f(rs[s]["fid"]) if s in rs else "—" for s in steps) + " |")
        L += ["", f"![FID vs steps]({rel}/fid_vs_steps.png)", "", f"![Latency]({rel}/latency.png)", "",
              f"![Samples]({rel}/sample_grid_compare.png)", "", f"![Loss curves]({rel}/loss_curves.png)", ""]
        L += ["### Per-class accuracy of generated samples (judge classifier)", "",
              "| Config | " + " | ".join(SHORT_NAMES) + " |", "|---|" + "---:|" * len(SHORT_NAMES)]
        for r in bench:
            L.append(f"| {r['name']} | " + " | ".join(_f(r.get(f'acc_{c}'), 2) for c in SHORT_NAMES) + " |")
        L.append("")
    if judge:
        L += [f"Judge classifier (ResNet-18, class-weighted) on real test images: accuracy {_f(judge.get('accuracy'), 3)}, "
              f"balanced accuracy {_f(judge.get('balanced_accuracy'), 3)}, macro-F1 {_f(judge.get('macro_f1'), 3)}. "
              "Class accuracy of samples should be read relative to these numbers.", ""]

    if summary:
        L += ["## Downstream utility: synthetic augmentation for rare lesions", "",
              "| Real data | Arm | Train images | Balanced acc ↑ | Macro-F1 ↑ | Accuracy | Seeds |",
              "|---|---|---:|---:|---:|---:|---:|"]
        for r in summary:
            L.append(f"| {r['setting']} | {r['arm']} | {r['n_train']} | {_pm(r, 'balanced_accuracy')} | "
                     f"{_pm(r, 'macro_f1')} | {_pm(r, 'accuracy')} | {r['n_seeds']} |")
        L += ["", "### Per-class recall (mean over seeds)", "",
              "| Real data | Arm | " + " | ".join(SHORT_NAMES) + " |", "|---|---|" + "---:|" * len(SHORT_NAMES)]
        for r in summary:
            L.append(f"| {r['setting']} | {r['arm']} | " +
                     " | ".join(_f(r[f'recall_{c}_mean'], 2) for c in SHORT_NAMES) + " |")
        L += ["", f"![Augmentation]({rel}/augmentation.png)", "",
              f"Synthetic samples used for augmentation: ![synthetic]({rel}/grids/augment_synthetic.png)", ""]
    if times:
        L += ["### Time to generate the synthetic set", "",
              "| Real data | Engine | Images | Seconds | Note |", "|---|---|---:|---:|---|"]
        for t in times:
            note = f"extrapolated from {t['measured_images']} images" if t["extrapolated"] == "True" else "measured"
            L.append(f"| {t['setting']} | {t['engine']} | {t['n_images']} | {_f(t['seconds'], 1)} | {note} |")
        L.append("")

    os.makedirs(docs_dir, exist_ok=True)
    path = os.path.join(docs_dir, "phase3_results.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {path}")
    return path


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--results_dir", default="results")
    p.add_argument("--docs_dir", default="docs")
    a = p.parse_args()
    write(a.results_dir, a.docs_dir)
